def fmt(v, d=3):
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "--"
    return f"{v:.{d}f}"


def load(name):
    p = os.path.join(RAW, name)
    if not os.path.exists(p):
        return None
    d = pd.read_csv(p)
    d["variant"] = d["variant"].fillna("")
    return d


def paired(df, a, b, metric, key="seed"):
    x = df[df.label == a].set_index(key)[metric]
    y = df[df.label == b].set_index(key)[metric]
    idx = x.index.intersection(y.index)
    diff = (x.loc[idx] - y.loc[idx]).to_numpy()
    rng = np.random.default_rng(0)
    boots = [rng.choice(diff, len(diff)).mean() for _ in range(10000)]
    lo, hi = np.percentile(boots, [2.5, 97.5])
    try:
        p = stats.wilcoxon(diff).pvalue if np.any(diff != 0) else 1.0
    except ValueError:
        p = np.nan
    dz = diff.mean() / diff.std(ddof=1) if diff.std(ddof=1) > 0 else np.inf * np.sign(diff.mean())
    return diff.mean(), lo, hi, p, dz, len(idx)


