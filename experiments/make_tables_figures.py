def latency_cdf():
    files = glob.glob(os.path.join(RAW, "tasks_main", "*.csv.gz"))
    if not files:
        return
    rows = []
    for f in files:
        t = pd.read_csv(f)
        lab = os.path.basename(f).split("__")[0]
        t["label"] = lab
        rows.append(t[t.kind == "verify"])
    t = pd.concat(rows)
    t["lat"] = t.t_delivered - t.origin
    t.groupby("label").lat.describe(percentiles=[.5, .9, .95, .99]).to_csv(os.path.join(TAB, "latency_quantiles.csv"))
    fig, ax = plt.subplots(figsize=(3.4, 2.3))
    styles = {"CLOUD-PER": ("--", "0.4"), "EDGE-PER": (":", "0.2"), "SOD-PT": ("-.", "0.5"),
              "SOD-PULL": ((0, (5, 1)), "0.6"), "BRISK": ("-", "0.0"), "BRISK+Watch": ((0, (1, 1)), "0.3")}
    for lab, (ls, c) in styles.items():
        x = np.sort(t[t.label == lab].lat.to_numpy())
        if len(x) == 0:
            continue
        ax.plot(x, np.arange(1, len(x) + 1) / len(x), ls=ls, color=c, lw=1.1, label=lab)
    ax.set_xscale("log")
    ax.set_xlabel("Urgent decision latency (s), log scale")
    ax.set_ylabel("CDF of delivered decisions")
    ax.legend(fontsize=6, loc="lower right")
    save(fig, "latency_cdf")
    for lab, tag in (("BRISK", "Brisk"), ("EDGE-PER", "Per"), ("CLOUD-PER", "Cloud"), ("SOD-PULL", "Pull")):
        x = t[t.label == lab].lat
        if len(x):
            macro(f"latNinetyNine{tag}", x.quantile(0.99), "{:.2f}")
            macro(f"fracRetried{tag}", 100 * (x > 2.0).mean(), "{:.1f}")


def pareto():
    p = load("pareto.csv")
    m = load("main.csv")
    if p is None:
        return
    a = p.groupby(["label", "variant"]).agg(
        energy=("energy_J_node_day", "mean"), err=("track_error", "mean"),
        hard=("track_hard_accuracy", "mean"), alarm=("verify_accuracy", "mean"),
        cot=("urgent_soil_correct_on_time", "mean"), rmse=("map_rmse", "mean"),
        err_sd=("track_error", "std"), n=("seed", "nunique")).reset_index()
    if m is not None:
        per = m[m.label == "EDGE-PER"]
        a = pd.concat([a, pd.DataFrame([{"label": "EDGE-PER", "variant": "periodic",
                                         "energy": per.energy_J_node_day.mean(), "err": per.track_error.mean(),
                                         "hard": per.track_hard_accuracy.mean(), "alarm": per.verify_accuracy.mean(),
                                         "cot": per.urgent_soil_correct_on_time.mean(), "rmse": per.map_rmse.mean(),
                                         "err_sd": per.track_error.std(), "n": per.seed.nunique()}])])
    a.to_csv(os.path.join(PROC, "pareto_means.csv"), index=False)
    fig, ax = plt.subplots(1, 2, figsize=(7.0, 2.4))
    for lab, mk, c in (("SOD-PT", "s", "0.55"), ("BRISK", "o", "0.0")):
        q = a[a.label == lab].sort_values("energy")
        ax[0].errorbar(q.energy, 100 * q.err, yerr=100 * q.err_sd, marker=mk, color=c, lw=0.9, ms=3.5,
                       capsize=2, label=lab)
        ax[1].plot(q.energy, q.hard, marker=mk, color=c, lw=0.9, ms=3.5, label=lab)
        for _, r in q.iterrows():
            off = (3, 4) if lab == "SOD-PT" else (-4, -9)
            ax[0].annotate(r.variant.replace("H=", ""), (r.energy, 100 * r.err), fontsize=5,
                           xytext=off, textcoords="offset points")
    per = a[a.label == "EDGE-PER"]
    if len(per):
        ax[0].scatter(per.energy, 100 * per.err, marker="^", color="0.3", s=18, label="periodic")
        ax[1].scatter(per.energy, per.hard, marker="^", color="0.3", s=18, label="periodic")
    from matplotlib.ticker import FixedLocator, NullLocator, FixedFormatter
    for x in ax:
        x.set_xscale("log")
        x.xaxis.set_major_locator(FixedLocator([0.2, 0.3, 0.5, 1.0, 2.0]))
        x.xaxis.set_major_formatter(FixedFormatter(["0.2", "0.3", "0.5", "1", "2"]))
        x.xaxis.set_minor_locator(NullLocator())
        x.set_xlabel("Radio energy (J/node/day), log scale")
    ax[0].set_ylabel("Zone-tracking error (%)")
    ax[1].set_ylabel("Accuracy on hard zone-hours")
    ax[0].legend(fontsize=6)
    fig.tight_layout()
    save(fig, "pareto")
    # iso-energy comparison text macros
    sod6 = a[(a.label == "SOD-PT") & (a.variant == "H=6h")]
    b324 = a[(a.label == "BRISK") & (a.variant == "H=3-24h")]
    if len(sod6) and len(b324):
        macro("isoSodEnergy", sod6.energy.iloc[0])
        macro("isoBriskEnergy", b324.energy.iloc[0])
        macro("isoSodErr", 100 * sod6.err.iloc[0])
        macro("isoBriskErr", 100 * b324.err.iloc[0])
    # equal-H_min pairing: SOD-PT with heartbeat H vs BRISK with H_min = H
    for sv, bv, tag in (("H=2h", "H=2-12h", "Two"), ("H=3h", "H=3-24h", "Three"), ("H=6h", "H=6-24h", "Six")):
        sp = a[(a.label == "SOD-PT") & (a.variant == sv)]
        bp = a[(a.label == "BRISK") & (a.variant == bv)]
        if len(sp) and len(bp):
            macro(f"pairSave{tag}", 100 * (sp.energy.iloc[0] - bp.energy.iloc[0]) / sp.energy.iloc[0], "{:.0f}")
            macro(f"pairErrSod{tag}", 100 * sp.err.iloc[0], "{:.2f}")
            macro(f"pairErrBrisk{tag}", 100 * bp.err.iloc[0], "{:.2f}")
            macro(f"pairEnSod{tag}", sp.energy.iloc[0])
            macro(f"pairEnBrisk{tag}", bp.energy.iloc[0])
            macro(f"pairRmseSod{tag}", 1000 * sp.rmse.iloc[0], "{:.2f}")
            macro(f"pairRmseBrisk{tag}", 1000 * bp.rmse.iloc[0], "{:.2f}")
    # dominance check: for each SOD point, is there a BRISK point with <= energy and <= error?
    dom = []
    for _, s in a[a.label == "SOD-PT"].iterrows():
        bb = a[(a.label == "BRISK") & (a.energy <= s.energy * 1.02)]
        best = bb.err.min() if len(bb) else np.nan
        dom.append({"sod": s.variant, "sod_energy": s.energy, "sod_err": s.err,
                    "best_brisk_err_at_leq_energy": best, "dominated": bool(len(bb) and best < s.err)})
    pd.DataFrame(dom).to_csv(os.path.join(TAB, "pareto_dominance.csv"), index=False)
    macro("nSodDominated", sum(x["dominated"] for x in dom), "{:d}")
    macro("nSodPoints", len(dom), "{:d}")
    lines = [r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
             r"Policy & Setting & Energy & Tracking err.\,(\%) & Hard acc. & Alarm acc. & Map RMSE ($10^{-3}$) \\",
             r"\midrule"]
    for _, r in a.sort_values(["label", "energy"]).iterrows():
        lines.append(f"{r.label} & {r.variant} & {r.energy:.2f} & {100 * r.err:.2f} & {r.hard:.3f} & "
                     f"{r.alarm:.3f} & {1000 * r.rmse:.2f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    open(os.path.join(GEN, "tab_pareto.tex"), "w").write("\n".join(lines))


